-- Requerimento de serviço e liberação de licença PDA.
--
-- Briefing: "a requisição de serviço vive em e-mail. O comercial manda por
-- e-mail, ela transforma num documento de requerimento, encaminha para a
-- trainer, e a trainer não registra nada no CRM." E: "pede-se a liberação, a
-- PDA responde em dois dias sem avisar que ficou pronto, e alguém precisa ir
-- olhar" — hoje numa planilha paralela de solicitado/liberado.
--
-- O requerimento segue o modelo usado hoje (planilha "Requerimento", ex. SCOR):
-- cliente, serviço/projeto, logística online e presencial com responsável por
-- item, cronograma por módulo e trainer, briefing e conclusão da trainer.

-- ---------------------------------------------------------------------------
-- 1. Requerimentos
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.requerimentos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  deal_id uuid REFERENCES public.deals(id) ON DELETE SET NULL,
  company_id uuid REFERENCES public.companies(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'solicitado' CHECK (status IN (
    'solicitado', 'em_preparacao', 'agendado', 'em_execucao', 'concluido', 'cancelado'
  )),
  -- Cliente
  plataforma text,
  contratante_nome text,
  contratante_email text,
  contratante_telefone text,
  contratante_cargo text,
  contratante_area text,
  contexto_cliente text,
  -- Serviço / projeto
  servico text NOT NULL,
  product_id uuid REFERENCES public.products(id) ON DELETE SET NULL,
  publico text,
  quantidade text,
  produtos_avaliacao text,
  formato text CHECK (formato IN ('online', 'presencial', 'hibrido')),
  carga_horaria text,
  data_texto text,
  horario_texto text,
  local text,
  cidade_uf text,
  base_avaliacao text,
  plataforma_transmissao text,
  materiais boolean,
  lista_participantes_url text,
  objetivo text,
  observacoes_adm text,
  -- Logística: [{grupo, item, necessario, responsavel, observacao}]
  logistica jsonb NOT NULL DEFAULT '[]'::jsonb,
  apoio_adm_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  -- Trainer
  briefing_em date,
  briefing_texto text,
  conclusao_em date,
  conclusao_texto text,
  criado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_requerimentos_deal ON public.requerimentos (deal_id);
CREATE INDEX IF NOT EXISTS idx_requerimentos_status ON public.requerimentos (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.requerimento_trainers (
  requerimento_id uuid NOT NULL REFERENCES public.requerimentos(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  PRIMARY KEY (requerimento_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.requerimento_sessoes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  requerimento_id uuid NOT NULL REFERENCES public.requerimentos(id) ON DELETE CASCADE,
  ordem smallint NOT NULL DEFAULT 0,
  titulo text NOT NULL,
  trainer_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  data date,
  horario text,
  formato text CHECK (formato IN ('online', 'presencial')),
  local text,
  status text NOT NULL DEFAULT 'a_confirmar'
    CHECK (status IN ('a_confirmar', 'confirmado', 'realizado', 'cancelado')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_requerimento_sessoes_req ON public.requerimento_sessoes (requerimento_id, ordem);
CREATE INDEX IF NOT EXISTS idx_requerimento_sessoes_trainer ON public.requerimento_sessoes (trainer_id, data);

DROP TRIGGER IF EXISTS requerimentos_touch ON public.requerimentos;
CREATE TRIGGER requerimentos_touch BEFORE UPDATE ON public.requerimentos
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();
DROP TRIGGER IF EXISTS requerimento_sessoes_touch ON public.requerimento_sessoes;
CREATE TRIGGER requerimento_sessoes_touch BEFORE UPDATE ON public.requerimento_sessoes
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

/** A trainer está escalada neste requerimento (lista ou alguma sessão)? */
CREATE OR REPLACE FUNCTION public.trainer_do_requerimento(_req uuid, _user uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT EXISTS (SELECT 1 FROM public.requerimento_trainers WHERE requerimento_id = _req AND user_id = _user)
      OR EXISTS (SELECT 1 FROM public.requerimento_sessoes WHERE requerimento_id = _req AND trainer_id = _user)
$$;
REVOKE EXECUTE ON FUNCTION public.trainer_do_requerimento(uuid, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trainer_do_requerimento(uuid, uuid) TO authenticated, service_role;

/** Quem lê o requerimento: ADM, comercial, CS e a trainer escalada. */
CREATE OR REPLACE FUNCTION public.pode_ver_requerimento(_req uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT public.pode_faturar(auth.uid())
      OR public.has_team(auth.uid(), 'comercial')
      OR public.has_team(auth.uid(), 'cs')
      OR public.trainer_do_requerimento(_req, auth.uid())
$$;
REVOKE EXECUTE ON FUNCTION public.pode_ver_requerimento(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pode_ver_requerimento(uuid) TO authenticated, service_role;

GRANT SELECT, INSERT, UPDATE ON public.requerimentos TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.requerimento_trainers, public.requerimento_sessoes TO authenticated;
GRANT ALL ON public.requerimentos, public.requerimento_trainers, public.requerimento_sessoes TO service_role;
ALTER TABLE public.requerimentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requerimento_trainers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requerimento_sessoes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "requerimentos_read" ON public.requerimentos;
CREATE POLICY "requerimentos_read" ON public.requerimentos
  FOR SELECT TO authenticated USING (public.pode_ver_requerimento(id));
-- O comercial abre (no nome dele); o ADM também pode abrir.
DROP POLICY IF EXISTS "requerimentos_insert" ON public.requerimentos;
CREATE POLICY "requerimentos_insert" ON public.requerimentos
  FOR INSERT TO authenticated WITH CHECK (
    criado_por = auth.uid()
    AND (public.has_team(auth.uid(), 'comercial') OR public.pode_faturar(auth.uid()))
  );
-- ADM edita sempre; quem abriu edita enquanto ainda não foi pego pelo ADM.
-- A trainer não edita a linha: briefing e conclusão passam pela função abaixo.
DROP POLICY IF EXISTS "requerimentos_update" ON public.requerimentos;
CREATE POLICY "requerimentos_update" ON public.requerimentos
  FOR UPDATE TO authenticated
  USING (public.pode_faturar(auth.uid()) OR (criado_por = auth.uid() AND status = 'solicitado'))
  WITH CHECK (public.pode_faturar(auth.uid()) OR (criado_por = auth.uid() AND status = 'solicitado'));

DROP POLICY IF EXISTS "requerimento_trainers_read" ON public.requerimento_trainers;
CREATE POLICY "requerimento_trainers_read" ON public.requerimento_trainers
  FOR SELECT TO authenticated USING (public.pode_ver_requerimento(requerimento_id));
DROP POLICY IF EXISTS "requerimento_trainers_write" ON public.requerimento_trainers;
CREATE POLICY "requerimento_trainers_write" ON public.requerimento_trainers
  FOR ALL TO authenticated
  USING (public.pode_faturar(auth.uid())) WITH CHECK (public.pode_faturar(auth.uid()));

DROP POLICY IF EXISTS "requerimento_sessoes_read" ON public.requerimento_sessoes;
CREATE POLICY "requerimento_sessoes_read" ON public.requerimento_sessoes
  FOR SELECT TO authenticated USING (public.pode_ver_requerimento(requerimento_id));
DROP POLICY IF EXISTS "requerimento_sessoes_write" ON public.requerimento_sessoes;
CREATE POLICY "requerimento_sessoes_write" ON public.requerimento_sessoes
  FOR ALL TO authenticated
  USING (public.pode_faturar(auth.uid())) WITH CHECK (public.pode_faturar(auth.uid()));

/**
 * O que a trainer atualiza: data e texto do briefing e da conclusão. Só os
 * campos dela — o resto do requerimento é do ADM.
 */
CREATE OR REPLACE FUNCTION public.trainer_registra_requerimento(
  _req uuid, _briefing_em date, _briefing_texto text, _conclusao_em date, _conclusao_texto text
)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT (public.trainer_do_requerimento(_req, auth.uid()) OR public.pode_faturar(auth.uid())) THEN
    RAISE EXCEPTION 'Só a trainer escalada (ou o ADM) registra briefing e conclusão';
  END IF;
  UPDATE public.requerimentos
     SET briefing_em = _briefing_em,
         briefing_texto = left(_briefing_texto, 20000),
         conclusao_em = _conclusao_em,
         conclusao_texto = left(_conclusao_texto, 20000),
         status = CASE WHEN _conclusao_em IS NOT NULL AND status <> 'cancelado' THEN 'concluido' ELSE status END
   WHERE id = _req;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.trainer_registra_requerimento(uuid, date, text, date, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trainer_registra_requerimento(uuid, date, text, date, text) TO authenticated;

/** A trainer confirma ou marca como realizada a sessão dela. */
CREATE OR REPLACE FUNCTION public.trainer_status_sessao(_sessao uuid, _status text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE v_req uuid; v_trainer uuid;
BEGIN
  IF _status NOT IN ('a_confirmar', 'confirmado', 'realizado') THEN
    RAISE EXCEPTION 'Status inválido';
  END IF;
  SELECT requerimento_id, trainer_id INTO v_req, v_trainer
    FROM public.requerimento_sessoes WHERE id = _sessao;
  IF v_req IS NULL THEN RAISE EXCEPTION 'Sessão não encontrada'; END IF;
  IF NOT (v_trainer = auth.uid() OR public.pode_faturar(auth.uid())) THEN
    RAISE EXCEPTION 'Só a trainer da sessão (ou o ADM) muda o status';
  END IF;
  UPDATE public.requerimento_sessoes SET status = _status WHERE id = _sessao;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.trainer_status_sessao(uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trainer_status_sessao(uuid, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- 2. Liberação de licença PDA
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.licencas_pda (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  deal_id uuid REFERENCES public.deals(id) ON DELETE SET NULL,
  company_id uuid REFERENCES public.companies(id) ON DELETE SET NULL,
  descricao text NOT NULL,
  tipo text NOT NULL DEFAULT 'licenca' CHECK (tipo IN ('licenca', 'recarga', 'partner', 'credito', 'sub_base')),
  quantidade integer CHECK (quantidade > 0),
  -- Contato responsável: é com ele que se cria o login do PDA.
  login_contato_id uuid REFERENCES public.contacts(id) ON DELETE SET NULL,
  login_email text,
  status text NOT NULL DEFAULT 'a_solicitar'
    CHECK (status IN ('a_solicitar', 'solicitado', 'liberado', 'cancelado')),
  solicitado_em timestamptz,
  solicitado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  liberado_em timestamptz,
  liberado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  observacao text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_licencas_pda_aberto
  ON public.licencas_pda (status, solicitado_em) WHERE status IN ('a_solicitar', 'solicitado');
CREATE INDEX IF NOT EXISTS idx_licencas_pda_deal ON public.licencas_pda (deal_id);
DROP TRIGGER IF EXISTS licencas_pda_touch ON public.licencas_pda;
CREATE TRIGGER licencas_pda_touch BEFORE UPDATE ON public.licencas_pda
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

GRANT SELECT, INSERT, UPDATE ON public.licencas_pda TO authenticated;
GRANT ALL ON public.licencas_pda TO service_role;
ALTER TABLE public.licencas_pda ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "licencas_pda_read" ON public.licencas_pda;
CREATE POLICY "licencas_pda_read" ON public.licencas_pda
  FOR SELECT TO authenticated USING (
    public.pode_faturar(auth.uid())
    OR public.has_team(auth.uid(), 'comercial')
    OR public.has_team(auth.uid(), 'cs')
  );
DROP POLICY IF EXISTS "licencas_pda_write" ON public.licencas_pda;
CREATE POLICY "licencas_pda_write" ON public.licencas_pda
  FOR ALL TO authenticated
  USING (public.pode_faturar(auth.uid())) WITH CHECK (public.pode_faturar(auth.uid()));
